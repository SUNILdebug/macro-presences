-- 14. VALIDER UNE PRÉSENCE — CODE APOGÉE
-- ============================================================

create or replace function public.validate_attendance(
    p_identifier varchar,
    p_qr_token uuid,
    p_confirmation_code varchar
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
    v_student public.students%rowtype;
    v_session public.sessions%rowtype;
begin
    select *
    into v_student
    from public.students
    where upper(student_identifier) = upper(trim(p_identifier))
    limit 1;

    if not found then
        return json_build_object(
            'success', false,
            'message', 'Code Apogée introuvable.'
        );
    end if;

    select *
    into v_session
    from public.sessions
    where qr_token = p_qr_token
    limit 1;

    if not found then
        return json_build_object(
            'success', false,
            'message', 'QR code invalide ou inconnu.'
        );
    end if;

    if now() < v_session.start_time then
        return json_build_object(
            'success', false,
            'message', 'La séance n''est pas encore ouverte.'
        );
    end if;

    if now() >= v_session.end_time then

        update public.sessions
        set status = 'EXPIREE'
        where id = v_session.id
          and status = 'ACTIVE';

        return json_build_object(
            'success', false,
            'message', 'Cette séance est terminée.'
        );
    end if;

    if v_session.status <> 'ACTIVE' then
        return json_build_object(
            'success', false,
            'message', 'Cette séance n''est plus active.'
        );
    end if;

    if coalesce(upper(trim(p_confirmation_code)), '')
       <> upper(trim(v_session.confirmation_code)) then

        return json_build_object(
            'success', false,
            'message', 'Code de confirmation incorrect.'
        );
    end if;

    if exists (
        select 1
        from public.attendances a
        where a.student_id = v_student.id
          and a.session_id = v_session.id
    ) then
        return json_build_object(
            'success', false,
            'message', 'Présence déjà enregistrée pour cette séance.'
        );
    end if;

    begin

        insert into public.attendances (
            student_id,
            session_id,
            validated_at
        )
        values (
            v_student.id,
            v_session.id,
            now()
        );

    exception
        when unique_violation then
            return json_build_object(
                'success', false,
                'message', 'Présence déjà enregistrée pour cette séance.'
            );
    end;

    return json_build_object(
        'success', true,
        'message', 'Présence enregistrée avec succès.',
        'student_identifier', v_student.student_identifier,
        'nom', v_student.nom,
        'prenom', v_student.prenom,
        'parcours', v_student.parcours,
        'validated_at', now()
    );
end;
$$;

