-- 8. INSCRIPTION ÉTUDIANT — CODE APOGÉE
-- ============================================================

drop function if exists public.register_student(varchar, varchar, varchar);

create or replace function public.register_student(
    p_nom varchar,
    p_prenom varchar,
    p_code_apogee varchar,
    p_parcours varchar
)
returns public.students
language plpgsql
security definer
set search_path = public
as $$
declare
    v_student public.students%rowtype;
    v_code varchar;
begin
    if not public.is_professor() then
        raise exception 'Accès réservé au professeur.';
    end if;

    if trim(coalesce(p_nom, '')) = '' then
        raise exception 'Le nom est obligatoire.';
    end if;

    if trim(coalesce(p_prenom, '')) = '' then
        raise exception 'Le prénom est obligatoire.';
    end if;

    v_code := upper(trim(coalesce(p_code_apogee, '')));

    if v_code = '' then
        raise exception 'Le Code Apogée est obligatoire.';
    end if;

    if p_parcours not in (
        'Analyse économique',
        'Économétrie appliquée'
    ) then
        raise exception 'Parcours invalide.';
    end if;

    insert into public.students (
        student_identifier,
        nom,
        prenom,
        parcours
    )
    values (
        v_code,
        trim(p_nom),
        trim(p_prenom),
        p_parcours
    )
    returning * into v_student;

    return v_student;

exception
    when unique_violation then
        raise exception 'Ce Code Apogée existe déjà.';
end;
$$;

