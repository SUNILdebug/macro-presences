create or replace function public.prevent_student_identifier_change()
returns trigger
language plpgsql
as $$
begin
    if new.student_identifier is distinct from old.student_identifier then
        raise exception 'Le Code Apogée ne peut pas être modifié.';
    end if;

    return new;
end;
$$;

