-- ============================================================
-- 10. OUVRIR UNE SÉANCE
-- ============================================================

create or replace function public.open_session(
    p_duration_minutes integer default 120
)
returns public.sessions
language plpgsql
security definer
set search_path = public
as $$
declare
    v_session public.sessions%rowtype;
    v_code varchar(3);
    v_now timestamptz := now();
begin
    if not public.is_professor() then
        raise exception 'Accès réservé au professeur.';
    end if;

    if p_duration_minutes < 5 or p_duration_minutes > 360 then
        raise exception 'La durée doit être comprise entre 5 et 360 minutes.';
    end if;

    update public.sessions
    set status = 'EXPIREE'
    where status = 'ACTIVE'
      and end_time <= v_now;

    if exists (
        select 1
        from public.sessions
        where status = 'ACTIVE'
    ) then
        raise exception 'Une séance est déjà active.';
    end if;

    select string_agg(
        substr(
            'ABCDEFGHJKLMNPQRSTUVWXYZ23456789',
            floor(random() * 32 + 1)::integer,
            1
        ),
        ''
    )
    into v_code
    from generate_series(1, 3);

    insert into public.sessions (
        course_name,
        session_date,
        start_time,
        end_time,
        confirmation_code,
        status
    )
    values (
        'Macroéconomie 3',
        (v_now at time zone 'Africa/Casablanca')::date,
        v_now,
        v_now + make_interval(mins => p_duration_minutes),
        v_code,
        'ACTIVE'
    )
    returning * into v_session;

    return v_session;
end;
$$;

-- ============================================================
-- 11. FERMER MANUELLEMENT UNE SÉANCE
-- ============================================================

create or replace function public.close_session(
    p_session_id bigint
)
returns public.sessions
language plpgsql
security definer
set search_path = public
as $$
declare
    v_session public.sessions%rowtype;
begin
    if not public.is_professor() then
        raise exception 'Accès réservé au professeur.';
    end if;

    update public.sessions
    set status = 'FERMEE'
    where id = p_session_id
      and status = 'ACTIVE'
    returning * into v_session;

    if not found then
        raise exception 'Séance introuvable ou déjà fermée.';
    end if;

    return v_session;
end;
$$;

-- ============================================================
-- 12. EXPIRER LES SÉANCES TERMINÉES
-- ============================================================

create or replace function public.expire_sessions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_count integer;
begin
    update public.sessions
    set status = 'EXPIREE'
    where status = 'ACTIVE'
      and end_time <= now();

    get diagnostics v_count = row_count;

    return v_count;
end;
$$;

-- ============================================================
-- 13. RÉCUPÉRER UNE SÉANCE DEPUIS LE QR
-- ============================================================

create or replace function public.get_session_by_qr_token(
    p_qr_token uuid
)
returns table (
    id bigint,
    course_name varchar,
    session_date date,
    start_time timestamptz,
    end_time timestamptz,
    qr_token uuid,
    status varchar
)
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.expire_sessions();

    return query
    select
        s.id,
        s.course_name,
        s.session_date,
        s.start_time,
        s.end_time,
        s.qr_token,
        s.status
    from public.sessions s
    where s.qr_token = p_qr_token
      and s.status = 'ACTIVE'
      and now() >= s.start_time
      and now() < s.end_time
    limit 1;
end;
$$;

